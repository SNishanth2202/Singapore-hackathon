import { expect, test } from '@playwright/test'

const api = 'http://127.0.0.1:5217/api/v1'
const accountId = 'synthetic:harbourline-logistics'

test('seeded dashboard, company filters, source catalogue and saved settings work in the browser', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Singtel Scout', level: 1 })).toBeVisible()
  await expect(page.getByText('Discovered', { exact: true }).first()).toBeVisible()
  const overview = await (await request.get(api + '/analytics/overview')).json()
  expect(overview.data.metrics.totalCompaniesDiscovered).toBeGreaterThanOrEqual(4)
  expect(overview.data.metrics.emailsAcceptedByProvider).toBeGreaterThan(0)
  await page.getByRole('combobox', { name: /^Reporting period/ }).selectOption('7')
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Company Intelligence', exact: true }).click()
  await page.getByPlaceholder('Search by company name or description…').fill('Cedar')
  await expect(page.getByText('Cedar Retail (Demo)', { exact: true })).toBeVisible()
  await expect(page.getByText('Meridian Cold Chain (Demo)', { exact: true })).toHaveCount(0)
  await page.getByText('Cedar Retail (Demo)', { exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Cedar Retail (Demo)', level: 1 })).toBeVisible()
  await page.goto('/settings')
  await page.getByRole('button', { name: 'Re-check', exact: true }).click()
  await page.getByRole('button', { name: 'Reload saved knowledge', exact: true }).click()
  await page.getByText('Explore the service catalogue', { exact: true }).click()
  await expect(page.getByRole('link', { name: 'Official reference' }).first()).toHaveAttribute('href', /^https:/)
  await page.getByLabel('Daily target (companies)', { exact: true }).fill('3')
  await page.getByRole('button', { name: 'Save settings', exact: true }).click()
  await expect.poll(async () => (await (await request.get(api + '/ai-management/settings')).json()).data.dailyTarget).toBe(3)
  await page.reload()
  await expect(page.getByLabel('Daily target (companies)', { exact: true })).toHaveValue('3')
  await page.screenshot({ path: '../.local/screenshots/showcase-settings.png', fullPage: true })
  expect(errors).toEqual([])
})

test('AI email activation, pause, resume, takeover, simulated reply and notifications work with the test outbox', async ({ page, request }) => {
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/ai-management')
  await expect(page.getByRole('link', { name: /Harbourline Logistics/ }).first()).toBeVisible()
  await page.getByRole('link', { name: /Harbourline Logistics/ }).first().click()
  await expect(page.getByRole('heading', { name: /Harbourline Logistics/, level: 1 })).toBeVisible()
  await page.getByRole('switch', { name: /Enable AI Management/ }).click()
  const activation = page.getByRole('dialog', { name: 'Enable AI Management' })
  await activation.getByRole('checkbox').nth(0).check()
  await activation.getByRole('checkbox').nth(1).check()
  await activation.getByRole('button', { name: 'Enable AI Management', exact: true }).click()
  await expect(activation).toHaveCount(0, { timeout: 120000 })
  const state = async () => (await (await request.get(api + '/ai-management/companies/' + encodeURIComponent(accountId))).json()).data
  await expect.poll(async () => (await state()).management.managementState, { timeout: 120000 }).toBe('ACTIVE')
  const conversation = await (await request.get(api + '/ai-management/companies/' + encodeURIComponent(accountId) + '/conversations')).json()
  expect(conversation.data.messages.some((message: { direction: string; synthetic: boolean }) => message.direction === 'OUTBOUND' && message.synthetic)).toBeTruthy()
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await expect.poll(async () => (await state()).management.managementState).toBe('PAUSED')
  await page.getByRole('button', { name: 'Resume AI', exact: true }).click()
  await expect.poll(async () => (await state()).management.managementState).toBe('ACTIVE')
  await page.getByRole('button', { name: 'Take over', exact: true }).click()
  await expect.poll(async () => (await state()).management.managementState).toBe('HUMAN_HANDOVER')
  await page.getByRole('button', { name: 'Resume AI', exact: true }).click()
  await expect.poll(async () => (await state()).management.managementState).toBe('ACTIVE')
  await page.getByPlaceholder('e.g. Does Singtel offer managed cybersecurity services?').fill('Please provide pricing and a proposal for regional connectivity. Can we schedule a meeting next week?')
  await page.getByRole('button', { name: 'Send simulated reply through the inbox', exact: true }).click()
  await expect.poll(async () => (await state()).notifications.filter((item: { requiresAction: boolean }) => item.requiresAction).length, { timeout: 120000 }).toBeGreaterThan(0)
  await page.goto('/ai-management?tab=attention')
  await expect(page.getByRole('link', { name: 'Open conversation', exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Take ownership', exact: true }).first().click()
  await expect(page.getByText(/You have taken ownership/)).toBeVisible()
  await page.getByRole('navigation', { name: 'AI Management sections' }).getByRole('button', { name: /Notifications/ }).click()
  await page.getByRole('button', { name: 'Mark all read', exact: true }).click()
  await expect.poll(async () => (await (await request.get(api + '/ai-management/notifications')).json()).meta.unreadCount).toBe(0)
  await page.getByRole('navigation', { name: 'AI Management sections' }).getByRole('button', { name: 'Follow-ups', exact: true }).click()
  await expect(page.getByRole('columnheader', { name: 'Due', exact: true })).toBeVisible()
  await page.screenshot({ path: '../.local/screenshots/showcase-ai-management.png', fullPage: true })
  const detail = await state()
  expect(detail.emailProvider.sendsRealEmail).toBe(false)
})

test('live company research collects public sources and renders a saved FreeLLM analysis', async ({ page }, testInfo) => {
  await page.goto('/companies')
  await page.getByLabel('Company name to research', { exact: true }).fill('Pall Corporation')
  const searchResponse = page.waitForResponse(response => response.url().endsWith('/ai/research/search') && response.request().method() === 'POST')
  const researchResponse = page.waitForResponse(response => response.url().endsWith('/ai/research') && response.request().method() === 'POST', { timeout: 120000 })
  await page.getByRole('button', { name: 'Research company', exact: true }).click()
  const search = await (await searchResponse).json()
  expect(search.success).toBe(true)
  if (!search.data.autoSelectId) await page.getByRole('button', { name: /Pall Corporation/ }).first().click()
  const collected = await researchResponse
  expect(collected.ok()).toBe(true)
  const record = (await collected.json()).data
  expect(record.sources.length).toBeGreaterThan(1)
  for (const source of record.sources.filter((item: { kind: string }) => item.kind === 'news_headline')) {
    expect(source.title).toMatch(/Pall Corp/i)
    expect(source.title).not.toMatch(/Pall Mall|Zeba Pall/i)
  }
  await expect(page.getByRole('heading', { name: /^Research: Pall/ })).toBeVisible()
  const analysis = page.getByRole('region', { name: 'AI company analysis' })
  await expect(analysis.getByText(/Live AI ·/)).toBeVisible({ timeout: 120000 })
  await expect(analysis.getByRole('alert')).toHaveCount(0)
  await analysis.getByRole('button', { name: 'Mark reviewed for this session', exact: true }).click()
  await expect(analysis.getByRole('button', { name: 'Marked as reviewed', exact: true })).toBeVisible()
  await page.screenshot({ path: '../.local/screenshots/showcase-live-research.png', fullPage: true })
  await testInfo.attach('Live research evidence', { body: JSON.stringify({ company: record.company.name, researchId: record.id, sourceCount: record.sources.length,
    urls: record.sources.map((source: { url: string }) => source.url) }), contentType: 'application/json' })
  await page.goto('/research-graph?researchId=' + record.id)
  const graph = page.getByRole('group', { name: 'Research evidence graph' })
  await expect(graph).toBeVisible()
  await graph.getByRole('button', { name: /^Company: Pall/ }).click()
  await expect(page.getByText('Pall Corporation', { exact: true }).last()).toBeVisible()
  await graph.getByRole('button', { name: /^Source:/ }).first().click()
  await expect(page.getByRole('link', { name: 'Open original source', exact: true })).toHaveAttribute('href', /^https:/)
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await expect(graph).toBeVisible()
  await page.screenshot({ path: '../.local/screenshots/showcase-evidence-graph.png', fullPage: true })
})
