test('initial load failure is retryable and an unavailable graph is clearly labelled', async ({ page }) => {
  let fail = true
  await page.route('**/api/v1/customer-graph', async route => {
    if (fail) return route.fulfill({ status: 503, json: { message: 'Temporary connection failure.' } })
    const response = await route.fetch(), snapshot = await response.json()
    return route.fulfill({ json: { ...snapshot, storage: { mode: 'local', synced: false, configured: true, message: 'Existing Neo4j graph is temporarily unavailable.' } } })
  })
  await page.goto('/customer-graph')
  await expect(page.getByRole('alert')).toContainText('Temporary connection failure')
  fail = false
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(page.locator('.cg-fact-card').first()).toBeVisible()
  await expect(page.getByText('Saved snapshot · graph pending', { exact: true })).toBeVisible()
  await expect(page.getByText('Existing Neo4j graph is temporarily unavailable.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Sync to Neo4j' })).toBeEnabled()
})

